/** Items that fit a type: the type's own first, then the ones for every type. */
export const forType = (n, extra = []) => {
  const all = [...extra, ...LIBRARY];
  if (!n) return all.filter((x) => !x.types.length);
  return [...all.filter((x) => x.types.includes(Number(n))), ...all.filter((x) => !x.types.length)];
};

